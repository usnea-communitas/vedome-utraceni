// scripts/compile.mjs — precompiles the JSX sources into one plain script (app.js)
// and copies the React production builds into vendor/, so the browser no longer
// downloads Babel (≈3 MB) and compiles the app on every visit.
//
//   npm install        (once)
//   npm run compile    (after every change to a .jsx file)
//
// The .jsx files stay the source of truth; app.js and vendor/ are generated and
// committed, so Vercel serves the site as plain static files without a build step.
import { transformSync } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

// order matters — same order as the old <script type="text/babel"> tags
const SOURCES = [
  'ios-frame.jsx', 'tweaks-panel.jsx', 'fa-core.jsx', 'fa-i18n.jsx', 'fa-forest.jsx',
  'fa-wizard.jsx', 'fa-ui.jsx', 'fa-tree.jsx', 'fa-invest.jsx', 'fa-prehled.jsx',
  'fa-add.jsx', 'fa-screens.jsx', 'fa-plan.jsx', 'fa-store.jsx', 'fa-onboard.jsx',
  'fa-settings.jsx', 'fa-app.jsx',
];

const joined = SOURCES.map(f => `// ── ${f} ──\n` + readFileSync(join(root, f), 'utf8')).join('\n;\n');
const out = transformSync(joined, {
  loader: 'jsx',
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  target: 'es2019',
  minifyWhitespace: true,
  minifySyntax: true,
  legalComments: 'none',
  charset: 'utf8',
});
writeFileSync(join(root, 'app.js'), '/* Vědomé utrácení — generated by scripts/compile.mjs from the .jsx sources. Do not edit. */\n' + out.code);

mkdirSync(join(root, 'vendor'), { recursive: true });
const reactDir = dirname(require.resolve('react/package.json'));
const domDir = dirname(require.resolve('react-dom/package.json'));
copyFileSync(join(reactDir, 'umd', 'react.production.min.js'), join(root, 'vendor', 'react.production.min.js'));
copyFileSync(join(domDir, 'umd', 'react-dom.production.min.js'), join(root, 'vendor', 'react-dom.production.min.js'));

console.log(`app.js: ${(out.code.length / 1024).toFixed(0)} kB from ${SOURCES.length} files; React ${require('react/package.json').version} → vendor/`);
