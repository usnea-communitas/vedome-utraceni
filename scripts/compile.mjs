// scripts/compile.mjs — precompiles the JSX sources into one plain script (app.js)
// and copies the React production builds into vendor/, so the browser no longer
// downloads Babel (≈3 MB) and compiles the app on every visit.
//
//   npm install        (once)
//   npm run compile    (after every change to a .jsx file)
//
// The .jsx files stay the source of truth; app.js and vendor/ are generated and
// committed, so Vercel serves the site as plain static files without a build step.
// It also stamps index.html (app.js?v=<content hash>, React ?v=<version>) and the
// same values into sw.js, so a browser never runs a new page with an old app.js.
import { transformSync } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

// order matters — same order as the old <script type="text/babel"> tags
const SOURCES = [
  'ios-frame.jsx', 'tweaks-panel.jsx', 'fa-core.jsx', 'fa-i18n.jsx', 'fa-forest.jsx',
  'fa-wizard.jsx', 'fa-ui.jsx', 'fa-tree.jsx', 'fa-invest.jsx', 'fa-prehled.jsx',
  'fa-add.jsx', 'fa-screens.jsx', 'fa-plan.jsx', 'fa-store.jsx', 'fa-onboard.jsx',
  'fa-settings.jsx', 'fa-app.jsx',
];

const joined = SOURCES.map(f => `// ── ${f} ──\n` + readFileSync(join(root, f), 'utf8')).join('\n;\n');
const out = transformSync(joined, {
  loader: 'jsx',
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  target: 'es2019',
  minifyWhitespace: true,
  minifySyntax: true,
  legalComments: 'none',
  charset: 'utf8',
});
const appCode = '/* Vědomé utrácení — generated by scripts/compile.mjs from the .jsx sources. Do not edit. */\n' + out.code;
writeFileSync(join(root, 'app.js'), appCode);

mkdirSync(join(root, 'vendor'), { recursive: true });
const reactDir = dirname(require.resolve('react/package.json'));
const domDir = dirname(require.resolve('react-dom/package.json'));
copyFileSync(join(reactDir, 'umd', 'react.production.min.js'), join(root, 'vendor', 'react.production.min.js'));
copyFileSync(join(domDir, 'umd', 'react-dom.production.min.js'), join(root, 'vendor', 'react-dom.production.min.js'));

// cache busting: the content hash of app.js and the React version go into the
// script URLs in index.html and into sw.js (its cache name and precache list)
const build = createHash('sha256').update(appCode).digest('hex').slice(0, 10);
const reactVersion = require('react/package.json').version;
function stamp(file, rules) {
  const path = join(root, file);
  let text = readFileSync(path, 'utf8');
  for (const [pattern, value] of rules) {
    if (!pattern.test(text)) throw new Error(`${file}: nothing matches ${pattern}`);
    text = text.replace(pattern, value);
  }
  writeFileSync(path, text);
}
stamp('index.html', [
  [/src="app\.js(\?v=[\w.-]+)?"/, `src="app.js?v=${build}"`],
  [/src="vendor\/react\.production\.min\.js(\?v=[\w.-]+)?"/, `src="vendor/react.production.min.js?v=${reactVersion}"`],
  [/src="vendor\/react-dom\.production\.min\.js(\?v=[\w.-]+)?"/, `src="vendor/react-dom.production.min.js?v=${reactVersion}"`],
]);
stamp('sw.js', [
  [/const BUILD = '[^']*';/, `const BUILD = '${build}';`],
  [/const REACT = '[^']*';/, `const REACT = '${reactVersion}';`],
]);

console.log(`app.js: ${(out.code.length / 1024).toFixed(0)} kB from ${SOURCES.length} files, build ${build}; React ${reactVersion} → vendor/`);
